@needs_live_corpus
class TheProjectionReadsTheProductionSchema(unittest.TestCase):
    """PHASE 6 (fourth audit). The projection read `e["id"]` and `e["at"]`; production
    emits `target` and `ts`. Every decision record on the real stream therefore read
    `None moved reported -> accepted` — a knowledge record naming no finding, in the one
    layer whose justification is provenance. And 133 of its 266 links pointed at records
    that did not exist, while `verify_bundle` reported the bundle healthy because it
    checked file checksums.

    Everything here runs on THIS REPOSITORY'S real state and event stream."""

    @classmethod
    def setUpClass(cls):
        envelope = xcheck_submodule("envelope")
        cls.state = state_mod.load_state(REPO / "audit")
        cls.events = envelope.read_events(REPO)
        cls.records = okf.project_bundle(cls.state, cls.events)
        cls.ids = {r["id"] for r in cls.records}
        cls.links = [(r["id"], rel, t) for r in cls.records
                     for rel, ts in r["links"].items() for t in ts]

    def test_the_real_stream_carries_target_and_ts_and_not_id_and_at(self):
        rows = [e for e in self.events if e.get("event") == "state_transition"]
        self.assertTrue(rows, "this checkout carries no transition events")
        for projection_name, emitted in okf.EVENT_FIELDS.items():
            have = [e for e in rows if e.get(emitted) is not None]
            fiction = [e for e in rows if e.get(projection_name) is not None]
            print(f"\n  SCHEMA     state_transition.{emitted:<8} on {len(have)} of "
                  f"{len(rows)}; .{projection_name:<3} (what the projection asked for) "
                  f"on {len(fiction)}")
            self.assertTrue(have, f"production does not emit {emitted}")
            self.assertEqual([], fiction,
                             f"an event carries {projection_name!r} — the emitter changed "
                             f"and the adapter has not")

    def test_a_decision_record_names_its_finding(self):
        decisions = [r for r in self.records if r["type"] == okf.DECISION]
        self.assertTrue(decisions, "the real stream produced no decision records")
        for rec in decisions:
            print(f"  DECISION   {rec['text']!r}  freshness={rec['freshness']}")
            self.assertNotIn("None moved", rec["text"],
                             "the decision record still names no finding")
            self.assertIsNotNone(rec["finding"])
            self.assertNotEqual(rec["freshness"], rec["source_revision"])

    def test_the_real_projection_has_no_dangling_links(self):
        dangling = [l for l in self.links if l[2] not in self.ids]
        by_source = {}
        for src, rel, _t in dangling:
            kind = next(r["type"] for r in self.records if r["id"] == src)
            by_source[(kind, rel)] = by_source.get((kind, rel), 0) + 1
        print(f"  LINKS      {len(self.links)} link(s), {len(dangling)} dangling"
              + (f" {by_source}" if dangling else ""))
        self.assertEqual([], dangling, f"{len(dangling)} of {len(self.links)} links "
                                       f"resolve to nothing: {by_source}")
        self.assertGreater(len(self.links), 200,
                           "a projection with almost no links cannot demonstrate that "
                           "its links resolve")

    def test_an_observation_id_is_built_in_exactly_one_place(self):
        """Structural, over the AST. The defect was two constructors that agreed and a
        third that did not, so counting them is the check — a test that only compared
        two ids would pass on any two that happened to match."""
        tree = ast.parse((REPO / "xcheck" / "okf.py").read_text(encoding="utf-8"))
        sites = []
        for node in ast.walk(tree):
            if not (isinstance(node, ast.Call) and isinstance(node.func, ast.Name)
                    and node.func.id == "_rid" and node.args):
                continue
            first = node.args[0]
            if isinstance(first, ast.Name) and first.id == "OBSERVATION":
                sites.append(node.lineno)
        print(f"  ONE ID     `_rid(OBSERVATION, ...)` at line(s) {sites}")
        self.assertEqual(1, len(sites),
                         f"an observation id is built at {len(sites)} places: {sites}")
        enclosing = [n.name for n in ast.walk(tree)
                     if isinstance(n, ast.FunctionDef)
                     and any(getattr(c, "lineno", None) in sites for c in ast.walk(n))]
        self.assertIn("observation_id", enclosing)

    def test_claim_and_hypothesis_both_reach_the_same_observation(self):
        """The two consumers of that one constructor, on real records: every finding's
        observation is pointed at by both its claim and, where a hypothesis covers its
        dimension, by that hypothesis."""
        obs = {r["id"] for r in self.records if r["type"] == okf.OBSERVATION}
        claims = {t for r in self.records if r["type"] == okf.CLAIM
                  for t in r["links"].get(okf.DERIVED_FROM, ())}
        hypos = {t for r in self.records if r["type"] == okf.HYPOTHESIS
                 for t in r["links"].get(okf.DERIVED_FROM, ())}
        print(f"  REACH      {len(obs)} observation(s); claims reach "
              f"{len(claims & obs)}, hypotheses reach {len(hypos & obs)}")
        self.assertEqual(set(), claims - obs)
        self.assertEqual(set(), hypos - obs)
        self.assertTrue(hypos, "no hypothesis linked anything")


@needs_live_corpus
class TheVerifierChecksWhatTheBundleSays(unittest.TestCase):
    """Checksums say the bytes are the bytes somebody wrote. They say nothing about
    whether what was written means anything, and that is how a bundle with 133 dangling
    links verified clean."""

    def setUp(self):
        fx, st, records = built()
        self.fx, self.records = fx, records
        okf.write_bundle(fx.root, records)

    def plant(self, mutate):
        """Rewrite `records.jsonl` and its manifest checksum, so only the SEMANTIC check
        can catch the plant. Leaving the checksum stale would let the old check fire and
        the test would pass for the wrong reason."""
        rows = [dict(r) for r in self.records]
        mutate(rows)
        okf.write_bundle(self.fx.root, rows)
        return okf.verify_bundle(self.fx.root)

    def test_CONTROL_a_correct_bundle_verifies_clean(self):
        self.assertEqual([], okf.verify_bundle(self.fx.root),
                         "the verifier refuses a bundle that is actually correct")
        print(f"\n  CONTROL    {len(self.records)} records verify clean")

    def test_a_dangling_link_is_caught(self):
        def mutate(rows):
            claim = next(r for r in rows if r["type"] == okf.CLAIM)
            claim["links"] = {okf.DERIVED_FROM: ["obse-deadbeef1234"]}
        problems = self.plant(mutate)
        self.assertTrue(any("obse-deadbeef1234" in p and "not a record in this bundle" in p
                            for p in problems), problems)
        self.dangling = problems
        print(f"  DANGLING   {problems[0][:130]}")

    def test_an_unknown_record_type_is_caught(self):
        problems = self.plant(lambda rows: rows[0].update(type="speculation"))
        self.assertTrue(any("unknown record type" in p and "speculation" in p
                            for p in problems), problems)
        print(f"  BAD TYPE   {problems[0][:130]}")

    def test_a_missing_required_field_is_caught(self):
        problems = self.plant(lambda rows: rows[0].pop("locator"))
        self.assertTrue(any("missing required field" in p and "locator" in p
                            for p in problems), problems)
        print(f"  NO FIELD   {problems[0][:130]}")

    def test_the_three_plants_produce_three_DISTINCT_messages(self):
        """N plants can cover fewer than N defects. Asserted on the messages themselves,
        because three arms that all read `the bundle is invalid` would be one check."""
        messages = {}
        for name, mutate in (
                ("dangling", lambda rows: rows[1].update(
                    links={okf.DERIVED_FROM: ["obse-deadbeef1234"]})),
                ("bad-type", lambda rows: rows[0].update(type="speculation")),
                ("no-field", lambda rows: rows[0].pop("locator"))):
            okf.write_bundle(self.fx.root, [dict(r) for r in self.records])
            messages[name] = self.plant(mutate)[0]
        self.assertEqual(3, len({m.split(":", 1)[1].strip()[:40]
                                 for m in messages.values()}),
                         f"the plants share a message: {messages}")

"""A derived knowledge layer, and the six things it must never become.

The audit called this the P2 feature most likely to quietly become a competing truth, so
the module is mostly refusals and this suite is mostly about the boundary rather than the
analysis. The audit's diagram is the specification:

    state.json + events -> projection -> analysis -> proposal -> human review
                                                                      |
                                                          an existing write verb -> state

Every arrow is one-way. What is asserted here, in the order a shortcut would appear:

  1. the bundle is a PROJECTION — reproducible from state.json plus the event stream
     alone, and byte-identical when re-derived from the same two inputs;
  2. six record types, each with real content and full provenance;
  3. a CONFLICT IS KEPT — two records that disagree both survive, joined by
     `conflicts_with`, with no last-wins anywhere;
  4. six forbidden effects, refused SEPARATELY — and proved distinct, because six arms
     that collapse into one cover one rule;
  5. a proposal changes no byte of state.json;
  6. off by default, generated by an explicit verb, with no vector store or graph
     database anywhere in the dependency set.
"""


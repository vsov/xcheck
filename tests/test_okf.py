class TheRealBundleStillVerifiesClean(unittest.TestCase):
    """Criterion 5. The project's own corpus, exported through the real entry point.

    Written to a TEMP root rather than `audit/okf/`: the operator's scope excludes
    `audit/` from being edited, and a control that had to modify the subject to run would
    be measuring a tree this run had changed.
    """

    @classmethod
    def setUpClass(cls):
        import shutil, tempfile
        from xcheck.envelope import read_events
        classes_mod = xcheck_submodule("classes")
        st = state_mod.load_state(REPO / "audit")
        cls.records = okf.project_bundle(st, read_events(REPO))
        found, _ungrouped = classes_mod.candidates(st, REPO)
        cls.proposals = classes_mod.proposals_for(found, cls.records) if found else []
        cls.tmp = Path(tempfile.mkdtemp(prefix="okf-control-"))
        (cls.tmp / "audit").mkdir(parents=True)
        cls.manifest = okf.write_bundle(cls.tmp, cls.records, proposals=cls.proposals)
        cls.addClassCleanup(shutil.rmtree, cls.tmp, ignore_errors=True)

    def test_it_verifies_clean_with_its_counts_printed(self):
        refs = sum(len(p.get(f) or ()) for p in self.proposals
                   for f in okf.PROPOSAL_REFS)
        links = sum(len(t) for r in self.records
                    for t in (r.get("links") or {}).values())
        problems = okf.verify_bundle(self.tmp)
        print(f"\n  REAL       {len(self.records)} record(s), {links} link(s), "
              f"{len(self.proposals)} proposal(s), {refs} evidence reference(s)")
        print(f"  REAL       manifest files {sorted(self.manifest['files'])} · "
              f"verify_bundle -> {problems}")
        self.assertEqual([], problems, "the real bundle no longer verifies")
        self.assertEqual(288, len(self.records))
        self.assertEqual(266, links)
        self.assertEqual(13, refs)

    def test_the_real_bundle_has_no_duplicate_ids(self):
        ids = [r["id"] for r in self.records]
        counted = collections.Counter(ids)
        worst = counted.most_common(1)[0]
        print(f"  REAL       {len(ids)} record(s), {len(counted)} distinct id(s); "
              f"most repeated: {worst[0]} x{worst[1]}")
        self.assertEqual(len(ids), len(counted))

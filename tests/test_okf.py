FINDINGS = [finding_record("F-0001", status="accepted", severity="critical"),
            finding_record("F-0002", status="reported", title="a second finding"),
            finding_record("F-0003", status="fixed", title="a third finding")]

# A human transition: `session_id` is absent, which is exactly what makes it a DECISION
# rather than something an agent did.
#
# PHASE 6 (fourth audit). These carried `id` and `at` — fields production has never

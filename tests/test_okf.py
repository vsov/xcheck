class AConflictIsKept(unittest.TestCase):
    """No last-wins anywhere. Two records that disagree about the same locator are two
    things someone said; picking a winner would be inventing a third."""

    def test_both_conflicting_records_survive_and_point_at_each_other(self):
        a = okf.knowledge_record(okf.CLAIM, "the lock is released on every path", 7,
                                 locator="xcheck/runner.py:100", finding="F-0009")
        b = okf.knowledge_record(okf.CLAIM, "the lock leaks on the timeout path", 7,
                                 locator="xcheck/runner.py:100", finding="F-0009")
        records = [a, b]
        pairs = okf.conflicts(records)
        self.assertEqual(1, len(pairs))
        self.assertEqual(2, len(records), "a record was dropped to resolve the conflict")
        self.assertIn(b["id"], a["links"][okf.CONFLICTS_WITH])
        self.assertIn(a["id"], b["links"][okf.CONFLICTS_WITH])
        print("KEPT CONFLICT — both survive, neither wins")
        print(f"  {a['id']}  {a['text']}")
        print(f"  {b['id']}  {b['text']}")
        print(f"  joined by `{okf.CONFLICTS_WITH}` in both directions; "
              f"{len(records)} records in, {len(records)} out")

    def test_the_module_contains_no_resolution_step(self):
        """Structural, not a spot check: nothing in the module names a winner."""
        text = Path(xcheck_submodule("okf").__file__).read_text(encoding="utf-8")
        body = "\n".join(l for l in text.splitlines()
                         if not l.strip().startswith("#") and "resolution" not in l
                         and "resolving" not in l and "resolve" not in l)
        for banned in ("last-wins", "lastwins", ".pop(", "del "):
            self.assertNotIn(banned, body, f"{banned} appears in a module that must keep "
                                           f"every conflicting record")


class TheBackChannelIsProposalOnly(unittest.TestCase):

    def test_all_six_forbidden_effects_are_refused(self):
        self.assertEqual(
            {"open-finding", "close-finding", "move-status", "weaken-policy",
             "replace-evidence", "raise-own-confidence"}, set(okf.FORBIDDEN))
        print("SIX REFUSALS")
        for effect in okf.FORBIDDEN:
            with self.assertRaises(PermissionError) as caught:
                okf.apply_effect(effect, "F-0001")
            msg = str(caught.exception)
            self.assertIn(okf.FORBIDDEN[effect][0], msg)
            print(f"  {effect:<22} {msg[:118]}")

    def test_the_six_refusals_are_distinct(self):
        """The control. Six arms that collapse into one cover one rule, so the messages
        are compared to each other and not only to a substring of themselves."""
        messages = {e: okf.refuse(e) for e in okf.FORBIDDEN}
        self.assertEqual(len(okf.FORBIDDEN), len(set(messages.values())),
                         "two forbidden effects produce the same refusal")
        # Stronger than distinctness: each message must name ITS OWN effect and no other
        # effect's distinguishing words, or six near-identical sentences would pass.
        for effect, msg in messages.items():
            for other, (what, _why) in okf.FORBIDDEN.items():
                if other != effect:
                    self.assertNotIn(what, msg,
                                     f"the {effect} refusal also describes {other}")
        with self.assertRaises(ValueError):
            okf.refuse("delete-the-repository")
        print(f"DISTINCT    {len(messages)} refusals, {len(set(messages.values()))} "
              f"unique, and none names another's effect")

    def test_a_proposal_holds_no_capability_and_names_an_existing_verb(self):
        fx, _st, records = built()
        self.addCleanup(fx.cleanup)
        p = okf.okf_proposal("accept", "F-0002",
                             "three findings share this dimension", records[:2],
                             verb="xcheck set-status F-0002 accepted")
        self.assertEqual("proposed", p["status"])
        self.assertIn("changes nothing", p["note"])
        self.assertNotIn("apply", p)
        print(f"PROPOSAL    verb={p['verb']!r} status={p['status']!r} "
              f"evidence={p['evidence']}")


class AProposalChangesNothing(unittest.TestCase):

    def test_generating_a_bundle_and_a_proposal_leaves_state_json_byte_identical(self):
        fx, st, records = built()
        self.addCleanup(fx.cleanup)
        path = Path(fx.audit) / "state.json"
        before = path.read_bytes()

        p = okf.okf_proposal("accept", "F-0002", "a proposal", records[:1],
                             verb="xcheck set-status F-0002 accepted")
        okf.write_bundle(fx.root, records, proposals=[p])
        after = path.read_bytes()
        self.assertEqual(before, after, "the bundle wrote to canonical state")
        self.assertEqual(st.state_revision,
                         state_mod.load_state(fx.audit).state_revision)
        print(f"UNCHANGED   state.json {len(before)} bytes before, {len(after)} after; "
              f"revision {st.state_revision} unmoved; "
              f"{sum(1 for _ in records)} records and 1 proposal written to audit/okf/")

    def test_the_only_path_to_state_is_an_existing_write_verb_run_by_a_human(self):
        """The proposal names a verb; running THAT verb is what moves state. The bundle
        has no other path, and the six refusals above are why."""
        fx, _st, records = built()
        self.addCleanup(fx.cleanup)
        path = Path(fx.audit) / "state.json"
        before = path.read_bytes()
        p = okf.okf_proposal("accept", "F-0002", "a proposal", records[:1],
                             verb="set-status F-0002 accepted")
        self.assertEqual(before, path.read_bytes())

        # A human runs the named verb. NOW state moves — through the same write path it
        # would have taken with no OKF in the picture.
        rc = subprocess.run([sys.executable, str(XCHECK), "--project", str(fx.root),
                             *p["verb"].split()], capture_output=True, text=True)
        self.assertEqual(0, rc.returncode, rc.stderr or rc.stdout)
        self.assertNotEqual(before, path.read_bytes())
        moved = state_mod.load_state(fx.audit)
        self.assertEqual("accepted",
                         next(r.status for r in moved.findings if r.id == "F-0002"))
        print(f"THE PATH    proposal -> human -> `xcheck {p['verb']}` -> F-0002 accepted "
              f"(revision now {moved.state_revision})")


class TheBundleIsDerived(unittest.TestCase):

    def test_the_projection_is_reproducible_from_state_and_events_alone(self):
        fx, st, first = built()
        self.addCleanup(fx.cleanup)
        again = okf.project_bundle(st, EVENTS, today="2026-09-03")
        self.assertEqual(json.dumps(first, sort_keys=True),
                         json.dumps(again, sort_keys=True))
        # And from a state loaded fresh off disk, which is the real claim: the only
        # inputs are the two files.
        reloaded = okf.project_bundle(state_mod.load_state(fx.audit), EVENTS,
                                      today="2026-09-03")
        self.assertEqual(json.dumps(first, sort_keys=True),
                         json.dumps(reloaded, sort_keys=True))
        print(f"REPRODUCIBLE {len(first)} records, byte-identical from a freshly loaded "
              f"state.json + events.jsonl")

    def test_the_manifest_checksums_every_file_and_catches_a_changed_byte(self):
        fx, _st, records = built()
        self.addCleanup(fx.cleanup)
        manifest = okf.write_bundle(fx.root, records)
        self.assertEqual([], okf.verify_bundle(fx.root))
        self.assertEqual(len(records), manifest["files"]["records.jsonl"]["rows"])

        rows = Path(okf.bundle_dir(fx.root), "records.jsonl")
        rows.write_text(rows.read_text(encoding="utf-8") + "{}\n", encoding="utf-8")
        problems = okf.verify_bundle(fx.root)
        self.assertEqual(["records.jsonl does not match its manifest checksum"], problems)
        print(f"MANIFEST    {problems[0]}")

    def test_no_vector_store_and_no_graph_database(self):
        """Read the module's AST, not its prose. The module's own docstring says "no
        vector store, no graph database, no embedding model", so a substring hunt over
        the source finds the words it is looking for in the sentence promising they are
        absent — the self-scanning-detector trap, in its purest form."""
        source = Path(xcheck_submodule("okf").__file__).read_text(encoding="utf-8")
        tree = ast.parse(source)
        imports = set()
        for node in ast.walk(tree):
            if isinstance(node, ast.Import):
                imports.update(a.name.split(".")[0] for a in node.names)
            elif isinstance(node, ast.ImportFrom) and node.module:
                imports.add(node.module.split(".")[0])
        self.assertEqual({"hashlib", "json", "datetime", "pathlib", "xcheck"},
                         imports, "the derived layer grew a dependency")

        # And no banned name appears as an identifier or a string VALUE — comments and
        # docstrings excluded, because those are where the promise is written.
        names = {n.id for n in ast.walk(tree) if isinstance(n, ast.Name)}
        names |= {n.attr for n in ast.walk(tree) if isinstance(n, ast.Attribute)}
        # Excluded by node IDENTITY, not by text: `ast.get_docstring` returns the
        # CLEANED docstring (dedented, stripped), which never equals the raw constant, so
        # subtracting the cleaned text removes nothing and the promise gets scanned.
        doc_nodes = set()
        for n in ast.walk(tree):
            if isinstance(n, (ast.Module, ast.FunctionDef, ast.ClassDef)):
                body = getattr(n, "body", None)
                if body and isinstance(body[0], ast.Expr) and \
                        isinstance(body[0].value, ast.Constant) and \
                        isinstance(body[0].value.value, str):
                    doc_nodes.add(id(body[0].value))
        strings = {n.value.lower() for n in ast.walk(tree)
                   if isinstance(n, ast.Constant) and isinstance(n.value, str)
                   and id(n) not in doc_nodes}
        for banned in ("faiss", "chroma", "neo4j", "networkx", "sqlite3", "embedding",
                       "vector"):
            self.assertNotIn(banned, {n.lower() for n in names}, banned)
            for text in strings:
                self.assertNotIn(banned, text, f"{banned} in a string value")
        print(f"DEPENDENCIES {sorted(imports)} — no vector store, no graph database, "
              f"asserted over the AST rather than over the prose that promises it")


